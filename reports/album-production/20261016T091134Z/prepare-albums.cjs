  const album={id,title,artist:'李詩民',provider:'Suno',model:'v6',language:'zh-TW',account:'subliminalsongbirds009',voice:{displayName:'2026/03/27',id:'b0593d92-dd06-4602-80fa-e701e89ee2d7',userConfirmed:true,liveVerifiedAt:'2026-10-16T09:15:00Z'},createdAt:new Date().toISOString(),timezone:'Asia/Taipei',status:'prepared',selectionPolicy:'one candidate per track, no audition requested',fictionalStories:true,tracks};
